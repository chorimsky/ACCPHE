/**
 * Bundles ./drizzle (journal + SQL) into src/db/migrations.generated.ts so production start-up
 * (src/server/bootstrap.ts) applies migrations without reading files at runtime. Hashes match drizzle-kit's, so
 * `npm run db:migrate` and the bundled runner share one __drizzle_migrations history.
 * Runs before every build (prebuild) and after `npm run db:generate`.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const journal = JSON.parse(readFileSync("drizzle/meta/_journal.json", "utf8"));
const migrations = journal.entries.map((e) => {
  const sql = readFileSync(`drizzle/${e.tag}.sql`, "utf8");
  return {
    tag: e.tag,
    when: e.when,
    hash: createHash("sha256").update(sql).digest("hex"),
    statements: sql
      .split("--> statement-breakpoint")
      .map((s) => s.trim())
      .filter(Boolean),
  };
});

const out = `// Generated by scripts/bundle-migrations.mjs from ./drizzle — do not edit.
export type BundledMigration = { tag: string; when: number; hash: string; statements: string[] };

export const MIGRATIONS: BundledMigration[] = ${JSON.stringify(migrations, null, 2)};
`;
writeFileSync("src/db/migrations.generated.ts", out);
console.log(`[bundle-migrations] ${migrations.length} migrations → src/db/migrations.generated.ts`);
